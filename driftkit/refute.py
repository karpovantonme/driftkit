def load_lessons(path: Optional[str]) -> List[dict]:
    """Suppression rules harvested from maintainer replies.

    This closes the loop: a rejection read by a human becomes a rule, and the
    same class of finding stops reaching submission. `lessons.py` collects them;
    the wording of a rule is written by a human rather than derived by a machine.
    """
    if not path or not os.path.isfile(path):
        return []
    try:
        with open(path, encoding="utf-8") as fh:
            data = json.load(fh)
    except (OSError, json.JSONDecodeError):
        return []
    out = []
    for r in data if isinstance(data, list) else []:
        pat = (r or {}).get("pattern")
        if not pat:
            continue
        try:
            out.append({"rx": re.compile(pat, re.I), "why": r.get("why", ""), "src": r.get("source", "")})
        except re.error:
            continue
    return out


# Tools whose findings are ABOUT A COMMENT rather than the code beside it.
# For them a coordinate inside a comment is a hit rather than evidence against.
ABOUT_DOCS = frozenset({"docdrift", "doxdrift", "transdrift", "deaddrift", "namedrift"})
DOC_KINDS = frozenset({"param", "tparam", "A", "B"})


def about_docs(finding: Any) -> bool:
    """Whether a finding is about documentation text.

    The rule "the coordinate points at a comment rather than code" holds for
    detectors that judge code. For `doxdrift` it is lethal: it reports the line
    of a `\\param` block, a comment by construction. On Boost.Geometry that wiped
    out 24 real findings out of 24, the only case besides ecologits where the
    refuter worked against us.
    """
    if not isinstance(finding, dict):
        return False
    if finding.get("tool") in ABOUT_DOCS:
        return True
    return finding.get("kind") in DOC_KINDS and ("func" in finding or "decl" in finding)


def refute_one(root: str, path: str, line: int, lessons: Sequence[dict] = (),
               doc_finding: bool = False) -> Tuple[List[str], List[str]]:
    """Reasons to consider a finding at this coordinate false, and what is unknown."""
    killed: List[str] = []
    unknown: List[str] = []

    if ARCHIVED.search(path):
        killed.append(f"archived path: {path}")
    if FIXTURES.search(path):
        killed.append(f"test data: {path}")

    full = _resolve(root, path)
    if full is None:
        unknown.append(f"file is not there: {path}")
        return killed, unknown

    text = common.read_text(full)
    if not text:
        unknown.append(f"file is empty or unreadable: {path}")
        return killed, unknown

    lines = text.splitlines()
    if line < 1 or line > len(lines):
        killed.append(f"coordinate past the end of the file: {path}:{line} of {len(lines)} lines")
        return killed, unknown

    if GENERATED.search(text[:4000]):
        killed.append("the file is generated, the generator is what needs fixing")

    window = "\n".join(lines[max(0, line - 4) : line + 3])
    if QUALIFIED.search(window):
        killed.append("a version or history caveat sits nearby, this may be intended")

    if (not doc_finding
            and os.path.splitext(path)[1].lower() in CODE_EXT
            and COMMENT_LINE.match(lines[line - 1])):
        killed.append("the coordinate points at a comment rather than code")

    for les in lessons:
        if les["rx"].search(window) or les["rx"].search(path):
            killed.append(f"lesson from review: {les['why'][:80]} ({les['src']})")

    return killed, unknown


def analyse(findings: Sequence[Any], root: str, report: Report,
            lessons: Sequence[dict] = ()) -> None:
    report.total = len(findings)
    by_file: Dict[str, List[int]] = defaultdict(list)

    for i, f in enumerate(findings):
        coords = coords_of(f)
        v = Verdict(index=i, subject=subject_of(f, i), coords=coords)
        if not coords:
            report.no_coords.append(v.subject)
            report.verdicts.append(v)
            continue
        for path, line in coords:
            by_file[path].append(i)
        # A finding counts as refuted only when ALL of its coordinates are.
        # Comparators carry two, and if one side is alive the finding is alive.
        doc = about_docs(f)
        per_coord = [refute_one(root, p, ln, lessons, doc) for p, ln in coords]
        if all(k for k, _u in per_coord):
            for k, _u in per_coord:
                v.killed_by.extend(k)
        for _k, u in per_coord:
            v.unknown.extend(u)
        report.verdicts.append(v)

    # A pile of findings in one file is one trouble rather than N. A kit-wide
    # rule derived three times: 115 mismatches in qdrant, 17 links on one page of
    # a Chinese translation, 81 "removed flags" in sarek.
    for path, idxs in sorted(by_file.items()):
        uniq = sorted(set(idxs))
        if len(uniq) >= CLUSTER_MIN:
            report.clusters.append(f"{path}: {len(uniq)} findings, read as one trouble")


def print_report(report: Report, verbose: bool = False) -> None:
    surv, killed = report.survivors, report.killed
    if surv:
        print(f"\n=== Survived refutation ({len(surv)}) ===")
        for v in surv:
            where = ", ".join(f"{p}:{ln}" for p, ln in v.coords[:2]) or "no coordinates"
            print(f"  [{v.index:3d}] {v.subject}")
            print(f"        {where}")
            for u in v.unknown:
                print(f"        unknown: {u}")

    if killed and verbose:
        print(f"\n=== Refuted ({len(killed)}) ===")
        for v in killed:
            print(f"  [{v.index:3d}] {v.subject}")
            for k in v.killed_by:
                print(f"        {k}")

    print("\n=== Coverage ===")
    print(f"  findings submitted:     {report.total}")
    print(f"  without coordinates:    {len(report.no_coords)} (nothing to refute against)")
    print(f"  refuted:                {len(killed)}")
    print(f"  rules from review:      {report.lessons_loaded}")
    print(f"  clustered:              {len(report.clusters)}")
    for c in report.clusters[:5]:
        print(f"    {c}")
    print(common.findings_line(len(surv), 0))
    print(stamp.line(__file__, ["common.py"]))


def main(argv: Optional[Sequence[str]] = None) -> int:
    ap = argparse.ArgumentParser(description="Try to kill a finding before it is submitted")
    ap.add_argument("--findings", required=True, help="JSON produced by any tool in the kit")
    ap.add_argument("--root", default=".", help="project root, when coordinates are relative")
    ap.add_argument("--survivors", help="write the survivors to JSON")
    ap.add_argument("--lessons", help="JSON of rules collected by lessons.py")
    ap.add_argument("--include-soft", action="store_true",
                    help="consider soft findings too")
    common.add_common_args(ap)
    args = ap.parse_args(argv)

    with open(args.findings, encoding="utf-8") as fh:
        data = json.load(fh)
    findings = data if isinstance(data, list) else data.get("findings", [])
    if not args.include_soft:
        # soft findings are already set aside as "needs reading by a human",
        # so refuting them changes nothing: they do not go to submission anyway
        findings = [f for f in findings if not isinstance(f, dict) or f.get("hard", True)]

    report = Report()
    lessons = load_lessons(args.lessons)
    report.lessons_loaded = len(lessons)
    analyse(findings, args.root, report, lessons)
    print_report(report, args.verbose)

    if args.survivors:
        with open(args.survivors, "w", encoding="utf-8") as fh:
            json.dump([findings[v.index] for v in report.survivors], fh, ensure_ascii=False, indent=1)
    if args.json:
        with open(args.json, "w", encoding="utf-8") as fh:
            json.dump(
                [
                    {
                        "hard": v.survives, "index": v.index, "subject": v.subject,
                        "coords": [f"{p}:{ln}" for p, ln in v.coords],
                        "killed_by": v.killed_by, "unknown": v.unknown,
                    }
                    for v in report.verdicts
                ],
                fh, ensure_ascii=False, indent=1,
            )
    return 1 if report.survivors else 0


if __name__ == "__main__":
    sys.exit(main())
